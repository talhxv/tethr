// Writes lib/booking/email-images.js: the confirmation email's foreground
// images as base64, read from public/email/. The sender embeds them in the
// message, so a PNG changed on disk reaches no inbox until this has run.
//
//   node scripts/build-email-images.mjs
//
// Re-run it whenever a PNG in public/email/ changes, and commit the result.
// The two background images (chain-corner.png, tether.png) are not embedded;
// mail clients only load those from a URL.

import { readFileSync, writeFileSync } from 'node:fs'
import { INLINE_IMAGE_FILES } from '../lib/booking/email.js'

const from = new URL('../public/email/', import.meta.url)
const out = new URL('../lib/booking/email-images.js', import.meta.url)

const lines = INLINE_IMAGE_FILES.map(file => `  '${file}': '${readFileSync(new URL(file, from)).toString('base64')}',`)

const source = `// Generated by scripts/build-email-images.mjs from public/email/. Do not edit by hand.
// The confirmation email's foreground images as base64, so the sender can
// embed them in the message itself instead of loading them from the site.
export const EMAIL_IMAGES = {
${lines.join('\n')}
}
`

writeFileSync(out, source)
console.log(`Wrote lib/booking/email-images.js: ${INLINE_IMAGE_FILES.length} images, ${Buffer.byteLength(source)} bytes`)
